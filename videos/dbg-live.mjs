import { createRequire } from 'node:module'
const require = createRequire('C:/Users/lenovo/AadiTech/Product/AadiProduct/MultiTenant/Aadi-MultiTenant-Platform/frontend/package.json')
const { chromium } = require('playwright')
const b = await chromium.launch({ channel: 'chrome', headless: true })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } }); const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('  PAGEERROR:', e.message.slice(0, 200)))
page.on('requestfailed', (r) => console.log('  REQFAILED:', r.url().slice(0, 100), r.failure()?.errorText))
page.on('console', (m) => console.log('  console:', m.type(), m.text().slice(0, 100)))
await page.goto('https://expenses.aaditechnology.com/'); await page.evaluate(() => navigator.serviceWorker.ready); await page.waitForTimeout(1500)
console.log('controller before reload:', await page.evaluate(() => !!navigator.serviceWorker.controller), '| caches:', await page.evaluate(async () => { const o = []; for (const k of await caches.keys()) for (const r of await (await caches.open(k)).keys()) o.push(new URL(r.url).pathname); return o }))
await ctx.setOffline(true)
await page.reload({ waitUntil: 'domcontentloaded' }).catch((e) => console.log('reload error', e.message.slice(0, 60)))
await page.waitForTimeout(2500)
console.log('title:', await page.title(), '| onLine:', await page.evaluate(() => navigator.onLine), '| bar:', await page.getByText(/You are offline/).count(), '| signin btn:', await page.getByRole('button', { name: 'Sign in', exact: true }).count())
console.log((await page.locator('#root').innerText()).slice(0, 160).replace(/\s+/g, ' '))
await b.close()
